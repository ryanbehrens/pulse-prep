export function describeExtra(raw, sys) {
  const side = raw.endsWith('.r') ? 'right' : raw.endsWith('.l') ? 'left' : null;
  const base = raw.replace(/\.(l|r)$/, '').replace(/[()*]/g, '').replace(/^_+/, '');
  let label = base.replace(/_/g, ' ').replace(/\s+/g, ' ').trim();
  label = label.replace(/^./, c => c.toUpperCase());
  let words = '';
  for (const [re, w] of ALIASES) if (re.test(base)) words += ' ' + w;
  const pearl = (PEARLS.find(([re]) => re.test(base)) || [])[1] || null;
  return {
    raw, base, side, pearl, system: sys, conn: MEMBRANE.test(base),
    region: null, sub: SYSTEMS[sys].label,
    label: side ? `${label} (${side})` : label,
    search: norm(`${label} ${base} ${words} ${SYSTEMS[sys].label} ${side || ''}`),
  };
}

